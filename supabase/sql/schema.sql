    depreciable_amount numeric(14,2) not null,
    accumulated_depreciation numeric(14,2) not null default 0,
    book_value numeric(14,2) not null,
    disposal_date date,
    disposal_amount numeric(14,2),
    paid_by text not null default 'corp' check (paid_by in ('corp','owner')),
    receipt_attached boolean not null default false,
    company_id bigint not null references public.companies (id) on delete cascade,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.depreciation_entries (
