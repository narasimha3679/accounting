create extension if not exists "pgcrypto";
create extension if not exists "uuid-ossp";

create or replace function public.handle_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = timezone('utc', now());
    return new;
end;
$$;

create table if not exists public.companies (
    id bigint generated by default as identity primary key,
    name text not null,
    business_number text not null unique,
    hst_number text,
    hst_registered boolean not null default false,
    fiscal_year_end date not null,
    small_business_rate numeric(5,4) not null default 0.1500,
    hst_rate numeric(5,4) not null default 0.1300,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.profiles (
    id bigint generated by default as identity primary key,
    auth_user_id uuid not null unique references auth.users (id) on delete cascade,
    email text not null unique,
    full_name text,
    role text not null default 'viewer' check (role in ('admin','accountant','viewer')),
    company_id bigint references public.companies (id) on delete set null,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.clients (
    id bigint generated by default as identity primary key,
    name text not null,
    contact_person text,
    email text,
    phone text,
    address text,
    hst_exempt boolean not null default false,
    company_id bigint not null references public.companies (id) on delete cascade,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.invoices (
    id bigint generated by default as identity primary key,
    invoice_number text not null unique,
    client_id bigint not null references public.clients (id) on delete restrict,
    issue_date date not null,
    due_date date not null,
    subtotal numeric(12,2) not null,
    hst_amount numeric(12,2) not null default 0,
    total numeric(12,2) not null,
    status text not null default 'draft' check (status in ('draft','sent','paid','overdue','cancelled')),
    paid_date date,
    description text,
    company_id bigint not null references public.companies (id) on delete cascade,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.invoice_items (
    id bigint generated by default as identity primary key,
    invoice_id bigint not null references public.invoices (id) on delete cascade,
    description text not null,
    quantity numeric(12,2) not null,
    unit_price numeric(12,2) not null,
    total numeric(12,2) not null,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.expense_categories (
    id bigint generated by default as identity primary key,
    name text not null,
    description text,
    company_id bigint references public.companies (id) on delete cascade,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.expenses (
    id bigint generated by default as identity primary key,
    description text not null,
    category_id bigint not null references public.expense_categories (id) on delete restrict,
    amount numeric(12,2) not null,
    hst_paid numeric(12,2) not null default 0,
    expense_date date not null,
    receipt_attached boolean not null default false,
    paid_by text not null default 'corp' check (paid_by in ('corp','owner')),
    company_id bigint not null references public.companies (id) on delete cascade,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.expense_files (
    id bigint generated by default as identity primary key,
    expense_id bigint not null references public.expenses (id) on delete cascade,
    storage_path text not null, -- e.g. expense-files/company-id/uuid.pdf
    original_name text not null,
    mime_type text not null,
    file_size integer not null,
    company_id bigint not null references public.companies (id) on delete cascade,
    created_at timestamptz not null default timezone('utc', now())
