    net_income_after_tax numeric(14,2) not null default 0,
    hst_collected numeric(14,2) not null default 0,
    hst_paid numeric(14,2) not null default 0,
    hst_remittance numeric(14,2) not null default 0,
    retained_earnings numeric(14,2) not null default 0,
    company_id bigint not null references public.companies (id) on delete cascade,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now()),
